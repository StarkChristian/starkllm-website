// Title and description of every page, in one place: used by the page itself, the Open Graph image (src/pages/og/)
// and the sitemap-independent checks. Older plain-HTML pages (manual, contact) keep their description in their head file.
import { pages } from '../i18n/pages';
import { langsFor, singlePages, type Lang } from '../i18n/ui';
import { pageMeta } from '../i18n/meta';
import { start, features, phone, privacy, changelog, about } from '../i18n/site';
import { download } from '../i18n/download';
import { help } from '../i18n/help';
import { tech } from '../i18n/tech';

const heads = import.meta.glob('../content-html/*.head*.html', { query: '?raw', import: 'default', eager: true }) as Record<string, string>;
const headOf = (name: string, lang: Lang) => heads[`../content-html/${name}.head${lang === 'en' ? '' : `.${lang}`}.html`];
const descIn = (html?: string) => html?.match(/name="description"\s+content="([^"]*)"/)?.[1];

export type PageMeta = { title: string; description?: string };

export function metaOf(lang: Lang, path: string): PageMeta {
  const def = pages[path];
  switch (def?.kind) {
    case 'home': return start[lang].meta;
    case 'features': return features[lang].meta;
    case 'phone': return phone[lang].meta;
    case 'privacy': return privacy[lang].meta;
    case 'changelog': return changelog[lang].meta;
    case 'download': return download[lang].meta as PageMeta;
    case 'help': return help[lang].meta as PageMeta;
    case 'tech': { const t = tech[lang][def.slug!]; return { title: t.title, description: t.lede }; }
    case 'about': return about[lang]?.meta ?? { title: pageMeta[lang].about.title, description: descIn(headOf('about', lang)) };
    case 'manual':
    case 'contact': { const m = pageMeta[lang][def.kind]; return { title: m.title, description: m.description ?? descIn(headOf(def.kind, lang)) }; }
    case 'legal': { const L = pageMeta[lang].legal!; return { title: L.title, description: L.description }; }
  }
  const single: Record<string, string> = { '/impressum': 'Impressum', '/datenschutz': 'Datenschutzerklärung', '/privacy-policy': 'Privacy policy', '/code-signing': 'Code signing policy' };
  return { title: `${single[path] ?? 'StarkLLM'} | StarkLLM` };
}

export const pageKey = (path: string) => (path === '/' ? 'home' : path.replace(/\.html$/, '').replace(/^\//, ''));

/** Path of the Open Graph image of a page: /og/<lang>-<page>.png (generated by src/pages/og/[slug].png.ts). */
export function ogPathFor(lang: Lang, path: string): string {
  const p = path.replace(/\.html$/, '');
  if (singlePages.includes(p)) return `/og/en-${pageKey(p)}.png`;
  if (p in pages && langsFor(p).includes(lang)) return `/og/${lang}-${pageKey(p)}.png`;
  return `/og/en-home.png`;
}
